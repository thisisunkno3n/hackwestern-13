#!/usr/bin/env python3
"""Writes third_party/atkinson/hud_fonts.c: the HUD's font set as C arrays (plan theme).

  python3 tools/gen_hud_fonts.py --family "Name" --sans-regular R.ttf --sans-medium M.ttf \
      --sans-semibold S.ttf --mono-regular MonoR.ttf --mono MonoM.ttf \
      [--out third_party/atkinson/hud_fonts.c]

A different family keeps the symbol names (hud_font_*): write it to its own folder with --out,
point CMakeLists.txt and scripts/build_pi.sh at that folder, and nothing else changes.

Inputs may be TTF, OTF or WOFF. With fontTools installed (pip install fonttools) each face is
subset to what the HUD prints (ASCII plus degree, plus-minus, middle dot and multiplication
signs, kern kept, no hinting) and written as plain TTF/OTF; without it TTF/OTF files are embedded
as they are. Put the family's licence and a README next to the generated file.
"""
import argparse, io, os, sys

UNICODES = list(range(0x20, 0x7F)) + [0xB0, 0xB1, 0xB7, 0xD7]


def load(path):
    try:
        from fontTools import subset
        from fontTools.ttLib import TTFont
    except ImportError:
        data = open(path, "rb").read()
        if data[:4] in (b"wOFF", b"wOF2"):
            sys.exit("%s is WOFF: install fonttools to convert it" % path)
        return data
    font = TTFont(path)
    opts = subset.Options()
    opts.layout_features = ["kern"]
    opts.hinting = False
    opts.desubroutinize = True
    opts.flavor = None
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    font.flavor = None
    buf = io.BytesIO()
    font.save(buf)
    return buf.getvalue()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--family", required=True)
    for k in ("sans-regular", "sans-medium", "sans-semibold", "mono-regular", "mono"):
        ap.add_argument("--" + k, required=True)
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--out", default=os.path.join(here, "..", "third_party", "atkinson", "hud_fonts.c"))
    a = ap.parse_args()
    out = ["/* Generated by tools/gen_hud_fonts.py: %s. Do not edit by hand; licence in" % a.family,
           " * LICENSE.txt next to this file. */", '#include "hud_fonts.h"', "",
           'const char hud_font_family[] = "%s";' % a.family.replace('"', "'"), ""]
    for name, path in (("sans_regular", a.sans_regular), ("sans_medium", a.sans_medium),
                       ("sans_semibold", a.sans_semibold), ("mono_regular", a.mono_regular),
                       ("mono", a.mono)):
        b = load(path)
        out.append("const unsigned char hud_font_%s[] = {" % name)
        for i in range(0, len(b), 16):
            out.append("    " + ",".join("0x%02x" % x for x in b[i:i + 16]) + ",")
        out.append("};")
        out.append("const unsigned int hud_font_%s_len = %d;" % (name, len(b)))
        out.append("")
        print("%-14s %7d bytes  %s" % (name, len(b), path))
    open(a.out, "w").write("\n".join(out))
    print("wrote", a.out)


if __name__ == "__main__":
    main()
